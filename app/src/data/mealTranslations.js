/**
 * 从烹饪步骤中提取关键词并返回带中文标注的片段
 * 返回 { text, zh } 数组，zh 为中文注解
 */
export function annotateInstruction(text) {
  if (!text) return [{ text: '', zh: null }]

  const lower = text.toLowerCase()
  const found = []

  for (const [verb, zh] of Object.entries(COOKING_VERBS)) {
    if (lower.includes(verb)) {
      found.push({ word: verb, zh })
    }
  }
  for (const [ing, zh] of Object.entries(INGREDIENT_ZH)) {
    if (lower.includes(ing)) {
      found.push({ word: ing, zh })
    }
  }

  // 按位置排序，去重
  found.sort((a, b) => lower.indexOf(a.word) - lower.indexOf(b.word))
  const unique = []
  let lastPos = -1
  for (const f of found) {
    const pos = lower.indexOf(f.word)
    if (pos === -1 || (pos >= lastPos && pos < lastPos + 10)) continue
    if (pos === lastPos) continue
    unique.push(f)
    lastPos = pos
  }

  if (!unique.length) return [{ text, zh: null }]

  // 分成动作和食材两组
  const verbs = unique.filter(f => COOKING_VERBS[f.word])
  const ings = unique.filter(f => INGREDIENT_ZH[f.word])

  let zh = ''
  if (verbs.length) {
    zh += '👨‍🍳 ' + verbs.slice(0, 3).map(v => v.zh).join(' → ')
  }
  if (ings.length && verbs.length) {
    const ingsShort = ings.slice(0, 3).map(i => i.zh).join('、')
    zh += ' | 食材：' + ingsShort
  } else if (ings.length) {
    zh += '🥘 食材：' + ings.slice(0, 5).map(i => i.zh).join('、')
  }

  return [{ text, zh }]
}

